import { createInterface } from 'node:readline';
import { Writable } from 'node:stream';
import { randomBytes,pbkdf2Sync } from 'node:crypto';
import { getStore } from './storage.mjs';
if(!process.stdin.isTTY)throw Error('Execute em terminal interativo: docker compose run --rm portal-maconico node setup.mjs');
const store=getStore('portal-maconico-auth');
if((await store.get('auth/users.json',{type:'json'}))?.length)throw Error('Administrador já existe. Use a recuperação documentada; não sobrescrever a base.');
let muted=false;const output=new Writable({write(chunk,encoding,callback){if(!muted)process.stdout.write(chunk,encoding);callback();}});
const rl=createInterface({input:process.stdin,output,terminal:true});
const ask=prompt=>new Promise(resolve=>rl.question(prompt,resolve));
const matricula=(await ask('Matrícula do administrador (2 a 12 dígitos): ')).trim();
const name=(await ask('Nome do administrador: ')).trim();
process.stdout.write('Senha (mínimo 14 caracteres): ');muted=true;const password=await ask('');muted=false;process.stdout.write('\n');
process.stdout.write('Confirme a senha: ');muted=true;const confirmation=await ask('');muted=false;process.stdout.write('\n');rl.close();
if(!/^\d{2,12}$/.test(matricula)||name.length<2||password.length<14||password.length>200||password!==confirmation)throw Error('Dados inválidos. Nenhum usuário criado.');
const salt=randomBytes(16).toString('base64url'),hash=pbkdf2Sync(password,salt,210000,32,'sha256').toString('base64url');
await store.setJSON('auth/users.json',[{matricula,name,memberId:Number(matricula),phone:'',active:true,degree:'mestre',portalAdmin:true,masonicOffice:'Sem cargo',initials:name.slice(0,2).toUpperCase(),passwordSalt:salt,passwordHash:hash,mustChangePassword:false,sessionVersion:1,createdAt:new Date().toISOString()}]);
await store.set('auth/session-secret.txt',randomBytes(48).toString('base64url'));
console.log('Administrador criado. Não compartilhe sua senha.');
